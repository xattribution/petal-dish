#!/usr/bin/env node
// Generate src/time/zones.gen.ts from the tz database's zone1970.tab (every IANA zone
// with the coordinates of its principal location and the ISO 3166 countries it covers)
// and iso-codes' ISO 3166-1 table (alpha-2 to the numeric codes Natural Earth uses).
// A site takes the zone of the nearest principal location among the zones of the
// country it stands in (sites carry no zone in SystemConfig).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = process.argv[2] ?? '/usr/share/zoneinfo/zone1970.tab';
const isoSrc = process.argv[3] ?? '/usr/share/iso-codes/json/iso_3166-1.json';
const numeric = new Map();
if (existsSync(isoSrc)) {
  for (const c of JSON.parse(readFileSync(isoSrc, 'utf8'))['3166-1']) numeric.set(c.alpha_2, c.numeric);
}
const parse = (s, degDigits) => {
  const sign = s[0] === '-' ? -1 : 1;
  const d = s.slice(1);
  const deg = Number(d.slice(0, degDigits));
  const min = Number(d.slice(degDigits, degDigits + 2));
  const sec = d.length > degDigits + 2 ? Number(d.slice(degDigits + 2, degDigits + 4)) : 0;
  return sign * (deg + min / 60 + sec / 3600);
};
const rows = [];
for (const line of readFileSync(src, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [codes, coord, tz] = line.split('\t');
  const m = coord.match(/^([+-]\d+)([+-]\d+)$/);
  if (!m) continue;
  const countries = codes.split(',').map((a) => numeric.get(a)).filter(Boolean);
  rows.push([tz, Math.round(parse(m[1], 2) * 1000) / 1000, Math.round(parse(m[2], 3) * 1000) / 1000, countries]);
}
rows.sort((a, b) => a[0].localeCompare(b[0]));
const out = resolve(here, '../src/time/zones.gen.ts');
writeFileSync(out, `// Generated by scripts/gen-zones.mjs from ${src.split('/').pop()} and ${isoSrc.split('/').pop()}. Do not edit.\n` +
  `/** [IANA zone, latitude deg, longitude deg, ISO 3166-1 numeric codes of the countries it covers]. */\n` +
  `export const ZONES: ReadonlyArray<readonly [string, number, number, readonly string[]]> = ${JSON.stringify(rows)};\n`);
console.log(`wrote ${out} (${rows.length} zones, ${numeric.size} country codes)`);
