#!/usr/bin/env node
// Generate src/api/types.gen.ts from the server's console JSON Schema.
//
//   npm run gen:types                      (runs ../.venv/bin/python -m petal_locate.server.api.schemas)
//   node scripts/gen-types.mjs schema.json (from a saved schema file)
//
// Conventions: every $defs entry becomes an exported interface (objects) or type alias;
// properties outside `required` are optional; string properties ending in `_ns` use the
// NsString alias (decimal-string nanoseconds that must never go through Number).
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../src/api/types.gen.ts');
const python = process.env.PETAL_PYTHON ?? resolve(here, '../../.venv/bin/python');
const text = process.argv[2]
  ? readFileSync(process.argv[2], 'utf8')
  : execFileSync(python, ['-m', 'petal_locate.server.api.schemas'], { encoding: 'utf8' });
const schema = JSON.parse(text);
const defs = schema.$defs ?? {};

const ident = (s) => (/^[A-Za-z_$][\w$]*$/.test(s) ? s : JSON.stringify(s));
const lit = (v) => JSON.stringify(v);

function typeOf(node, propName = '') {
  if (!node || Object.keys(node).length === 0) return 'unknown';
  if (node.$ref) return node.$ref.split('/').pop();
  if (node.const !== undefined) return lit(node.const);
  if (node.enum) return node.enum.map(lit).join(' | ');
  const union = node.anyOf ?? node.oneOf;
  if (union) {
    const parts = [...new Set(union.map((n) => typeOf(n, propName)))];
    return parts.join(' | ');
  }
  if (Array.isArray(node.type)) return node.type.map((t) => typeOf({ ...node, type: t }, propName)).join(' | ');
  switch (node.type) {
    case 'string':
      return propName.endsWith('_ns') ? 'NsString' : 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array': {
      if (node.prefixItems) return `[${node.prefixItems.map((n) => typeOf(n)).join(', ')}]`;
      const inner = typeOf(node.items ?? {});
      return /[|&]/.test(inner) ? `Array<${inner}>` : `${inner}[]`;
    }
    case 'object': {
      if (node.properties) return objectBody(node, '  ');
      if (node.additionalProperties && typeof node.additionalProperties === 'object')
        return `Record<string, ${typeOf(node.additionalProperties)}>`;
      return 'Record<string, unknown>';
    }
    default:
      return 'unknown';
  }
}

function doc(text, indent) {
  if (!text) return '';
  const lines = String(text).trim().split('\n');
  return `${indent}/**\n${lines.map((l) => `${indent} * ${l.replace(/\*\//g, '* /')}`.trimEnd()).join('\n')}\n${indent} */\n`;
}

function objectBody(node, indent) {
  const req = new Set(node.required ?? []);
  const lines = Object.entries(node.properties).map(([name, prop]) => {
    const opt = req.has(name) ? '' : '?';
    return `${doc(prop.description, indent)}${indent}${ident(name)}${opt}: ${typeOf(prop, name)};`;
  });
  return `{\n${lines.join('\n')}\n${indent.slice(2)}}`;
}

const names = Object.keys(defs).sort();
let body = `// Generated by scripts/gen-types.mjs from petal_locate.server.api.schemas. Do not edit.\n`;
body += `// Regenerate with: npm run gen:types\n\n`;
body += `/** Absolute UTC time in integer nanoseconds as a decimal string. Never pass through Number. */\n`;
body += `export type NsString = string;\n\n`;
for (const name of names) {
  const node = defs[name];
  body += doc(node.description, '');
  if (node.type === 'object' && node.properties) body += `export interface ${name} ${objectBody(node, '  ')}\n\n`;
  else body += `export type ${name} = ${typeOf(node)};\n\n`;
}
writeFileSync(out, body);
console.log(`wrote ${out} (${names.length} types)`);
